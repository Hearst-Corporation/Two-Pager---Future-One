const OPERATORS_BY_ID = Object.fromEntries(OPERATORS.map(o => [o.id, o]));

function fmtUsd(n) {
  if (n == null) return '—';
  if (Math.abs(n) >= 1e9) return `$${(n / 1e9).toFixed(2)}B`;
  if (Math.abs(n) >= 1e6) return `$${(n / 1e6).toFixed(2)}M`;
  if (Math.abs(n) >= 1e3) return `$${(n / 1e3).toFixed(1)}k`;
  return `$${n.toFixed(0)}`;
}
function fmtPct(n) {
  if (n == null) return '—';
  return `${(n * 100).toFixed(1)}%`;
}
function fmtDate(d) {
  if (!d) return '—';
  try { return new Date(d).toLocaleDateString(); } catch { return d; }
}

function exportJson(inventory) {
  if (!inventory) return;
  const blob = new Blob([JSON.stringify(inventory, null, 2)], { type: 'application/json' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `engine-audit-${new Date().toISOString().slice(0, 10)}.json`;
  a.click();
  URL.revokeObjectURL(url);
}

function exportReport(inventory) {
  if (!inventory) return;
  const date = new Date().toISOString().slice(0, 10);
  const sources = inventory.catalogs?.public_sources || {};
  const magics = inventory.magic_numbers || [];
  const tables = inventory.db_tables || [];
  const warnings = inventory.health_warnings || [];
  const summary = inventory.health_summary || {};
  const p0 = summary.p0 ?? 0;
  const p1 = summary.p1 ?? 0;
  const p2 = summary.p2 ?? 0;

  // Sources by operator
  const byOperator = {};
  (PUBLIC_SOURCES_LIBRARY || []).forEach(s => {
    byOperator[s.operator_id] = (byOperator[s.operator_id] || 0) + 1;
  });

  const operatorRows = Object.entries(byOperator)
    .sort((a, b) => b[1] - a[1])
    .map(([op, count]) => `| ${OPERATORS_BY_ID[op]?.label || op} | ${count} |`)
    .join('\n');

  const magicRows = magics
    .map(m => `| ${m.label} | ${m.value} | ${m.file}:${m.line} | ${m.suggested_action || '—'} |`)
    .join('\n');

  const tableRows = tables
    .map(t => `| ${t.table} | ${t.error ? 'error' : t.count} | ${t.latest_change_at ? new Date(t.latest_change_at).toLocaleString() : '—'} |`)
    .join('\n');

  const p0Warnings = warnings.filter(w => w.severity === 'P0');
  const p1Warnings = warnings.filter(w => w.severity === 'P1');
  const p2Warnings = warnings.filter(w => w.severity === 'P2');

  const warnSection = (label, list) => {
    if (list.length === 0) return `## Warnings — ${label}\n\n_None_\n`;
    return `## Warnings — ${label}\n\n${list.map(w => `- [${w.label}] (${w.ref || '—'}) — ${w.detail || ''}`).join('\n')}\n`;
  };

  const md = `# Engine Audit Report — ${date}

## Summary
- Public sources: ${sources.total ?? PUBLIC_SOURCES_LIBRARY.length} (avg confidence ${sources.avg_confidence ?? '—'}/5)
- Deal archetypes: ${inventory.catalogs?.deal_archetypes?.total ?? DEAL_ARCHETYPES.length}
- Magic numbers: ${magics.length}
- DB tables OK: ${tables.filter(t => !t.error).length}/${tables.length}
- Warnings: ${p0} P0 · ${p1} P1 · ${p2} P2

## Sources by operator
| Operator | Count |
|---|---|
${operatorRows}

## Magic numbers
| Label | Value | File:Line | Suggested action |
|---|---|---|---|
${magicRows || '_None_'}

## DB tables
| Table | Rows | Latest change |
|---|---|---|
${tableRows || '_None_'}

${warnSection('P0', p0Warnings)}
${warnSection('P1', p1Warnings)}
${warnSection('P2', p2Warnings)}
---
Generated by /admin/hearst/engine
`;

  const blob = new Blob([md], { type: 'text/markdown' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `engine-audit-report-${date}.md`;
  a.click();
  URL.revokeObjectURL(url);
}

