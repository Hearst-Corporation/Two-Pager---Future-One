// SOURCES (PUBLIC_SOURCES_LIBRARY)
// ────────────────────────────────────────────────────────────
function SourcesTab() {
  const [operatorFilter, setOperatorFilter] = useState('');
  const [confidenceFilter, setConfidenceFilter] = useState(0);
  const [geoFilter, setGeoFilter] = useState('');
  const [search, setSearch] = useState('');

  const operators = useMemo(() => {
    const set = new Set(PUBLIC_SOURCES_LIBRARY.map(s => s.operator_id));
    return Array.from(set).sort();
  }, []);

  const filtered = useMemo(() => {
    return PUBLIC_SOURCES_LIBRARY.filter(s => {
      if (operatorFilter && s.operator_id !== operatorFilter) return false;
      if (confidenceFilter && (s.confidence_score || 0) < confidenceFilter) return false;
      if (geoFilter) {
        const g = (s.geography || '').toLowerCase();
        if (geoFilter === 'qatar' && !g.includes('qatar')) return false;
        if (geoFilter === 'mena' && !(g.includes('mena') || g.includes('gulf'))) return false;
        if (geoFilter === 'global' && (g.includes('qatar') || g.includes('mena'))) return false;
      }
      if (search) {
        const q = search.toLowerCase();
        const blob = `${s.metric_name} ${s.metric_id} ${s.source_name} ${s.operator_id}`.toLowerCase();
        if (!blob.includes(q)) return false;
      }
      return true;
    });
  }, [operatorFilter, confidenceFilter, geoFilter, search]);

  return (
    <section style={S.section}>
      <h2 style={S.h2}>Public Sources Library</h2>
      <p style={S.p}>
        {PUBLIC_SOURCES_LIBRARY.length} datapoints externes utilisés par <code>bootstrapScenarioFromSources</code>{' '}
        pour pré-remplir les scénarios. Médiane robuste par <code>metric_id</code>, filtre Qatar→MENA→Global en cascade.
      </p>

      <div style={S.filterRow}>
        <input
          type="search"
          placeholder="Search metric, source, operator…"
          value={search}
          onChange={e => setSearch(e.target.value)}
          style={S.searchInput}
        />
        <select value={operatorFilter} onChange={e => setOperatorFilter(e.target.value)} style={S.select}>
          <option value="">All operators</option>
          {operators.map(op => <option key={op} value={op}>{OPERATORS_BY_ID[op]?.label || op}</option>)}
        </select>
        <select value={geoFilter} onChange={e => setGeoFilter(e.target.value)} style={S.select}>
          <option value="">All regions</option>
          <option value="qatar">Qatar</option>
          <option value="mena">MENA/Gulf</option>
          <option value="global">Global only</option>
        </select>
        <select value={confidenceFilter} onChange={e => setConfidenceFilter(Number(e.target.value))} style={S.select}>
          <option value={0}>Any confidence</option>
          <option value={3}>≥ 3</option>
          <option value={4}>≥ 4</option>
          <option value={5}>= 5 (high)</option>
        </select>
        <span style={S.countPill}>{filtered.length} / {PUBLIC_SOURCES_LIBRARY.length}</span>
      </div>

      <div style={S.tableWrap}>
        <table style={S.table}>
          <thead>
            <tr>
              <th style={S.th}>Operator</th>
              <th style={S.th}>Metric</th>
              <th style={S.thNum}>Value</th>
              <th style={S.th}>Unit</th>
              <th style={S.th}>Geo</th>
              <th style={S.thNum}>Conf</th>
              <th style={S.th}>Published</th>
              <th style={S.th}>Source</th>
            </tr>
          </thead>
          <tbody>
            {filtered.map(s => (
              <tr key={s.id}>
                <td style={S.td}>{OPERATORS_BY_ID[s.operator_id]?.label || s.operator_id}</td>
                <td style={S.tdMono}>{s.metric_name}<div style={S.tinyMono}>{s.metric_id}</div></td>
                <td style={S.tdNum}>{typeof s.value === 'number' && s.value < 1 ? s.value.toFixed(3) : (s.value?.toLocaleString?.() ?? '—')}</td>
                <td style={S.td}>{s.unit}</td>
                <td style={S.td}>{s.geography}</td>
                <td style={S.tdNum}>
                  <ConfidenceDot score={s.confidence_score} />
                </td>
                <td style={S.td}>{fmtDate(s.date_published)}</td>
                <td style={S.td}>
                  {s.url ? <a href={s.url} target="_blank" rel="noreferrer" style={S.link}>{s.source_name}</a> : s.source_name}
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </section>
  );
}

function ConfidenceDot({ score }) {
  const s = score ?? 0;
  const dots = [1, 2, 3, 4, 5].map(i => (
    <span key={i} style={{ ...S.confDot, background: i <= s ? 'var(--cp-text-primary)' : 'var(--cp-border)' }} />
  ));
  return <span style={S.confDots}>{dots}</span>;
}

